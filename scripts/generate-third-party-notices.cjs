const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');

function renderNotices(root) {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'licenses/third-party.json'), 'utf8'));
  if (catalog.schemaVersion !== 1) throw new Error('Unsupported third-party notice schema');
  const entries = Object.entries(lock.packages).filter(([name]) => name);
  const packages = new Map(catalog.packages.map((pkg) => [pkg.path, pkg]));
  if (packages.size !== catalog.packages.length || packages.size !== entries.length)
    throw new Error('Third-party package inventory does not match package-lock.json');
  const used = new Map();
  for (const [name, entry] of entries) {
    const pkg = packages.get(name);
    if (
      !pkg ||
      pkg.version !== entry.version ||
      pkg.integrity !== entry.integrity ||
      pkg.resolved !== entry.resolved ||
      pkg.dev !== !!entry.dev ||
      pkg.declaredLicense !== (entry.license || null) ||
      !pkg.notices.length
    )
      throw new Error('Refresh third-party notices for ' + name);
    if (!entry.license && !pkg.effectiveLicense)
      throw new Error('Missing license resolution: ' + name);
    if (pkg.upstreamNoticeMissing && !pkg.dev)
      throw new Error('Runtime notice is incomplete: ' + name);
    for (const notice of pkg.notices) {
      const text = catalog.texts[notice.text];
      if (
        !text ||
        createHash('sha256').update(text).digest('hex') !== notice.text ||
        !notice.source
      )
        throw new Error('Invalid notice text or source for ' + name);
      if (!used.has(notice.text)) used.set(notice.text, new Set());
      used.get(notice.text).add(notice.source);
    }
  }
  const lines = [
    '# Third-party notices',
    '',
    'The project LICENSE applies to original Batch Studio code, documentation and templates.',
    'Third-party components retain their own licenses. This inventory includes runtime, optional',
    'and development npm dependencies in package-lock.json; listing a tool does not mean it is shipped.',
    '',
    'Upstream notices are reproduced below and deduplicated by their SHA-256. Source URLs identify',
    'the locked archives or upstream commits. Supplied-by notices come from the parent project.',
    '',
    'Electron binaries also require their LICENSE and LICENSES.chromium.html. The runtime copy',
    'step preserves these separately under dist-electron/licenses/electron/. External ComfyUI,',
    'CLIs, model weights and OS/container packages are not covered by the project MIT license.',
    '',
    'Two development packages lack an upstream full license notice; their entries explicitly',
    'record this limitation. Obtain upstream notices before redistributing these tools/binaries.',
    'See docs/operations/licensing.md for scope, refresh and distribution instructions.',
    '',
    'Generated by scripts/generate-third-party-notices.cjs. Do not edit this file manually.',
    '',
    '## Locked packages',
    '',
    '| Package path | Version | License declaration / resolution | Scope | Notices |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const pkg of [...packages.values()].sort((a, b) => a.path.localeCompare(b.path))) {
    const license = pkg.effectiveLicense || pkg.declaredLicense;
    const scope = pkg.dev ? 'development' : 'runtime / optional';
    const notices = pkg.notices
      .map((n) => '[' + n.text.slice(0, 12) + '](#notice-' + n.text + ')')
      .join(', ');
    lines.push(
      '| ' +
        pkg.path +
        ' | ' +
        pkg.version +
        ' | ' +
        license +
        ' | ' +
        scope +
        ' | ' +
        notices +
        ' |',
    );
  }
  const missing = [...packages.values()].filter((pkg) => pkg.upstreamNoticeMissing);
  if (missing.length) {
    lines.push('', '## Missing upstream notices', '');
    for (const pkg of missing)
      lines.push('- ' + pkg.path + ': upstream full notice unavailable; declaration only.');
  }
  lines.push('', '## License texts and notices', '');
  for (const [hash, sources] of [...used].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push('<a id="notice-' + hash + '"></a>', '', '### Notice ' + hash, '');
    for (const source of [...sources].sort()) lines.push('- Source: ' + source);
    lines.push('', '~~~~text', catalog.texts[hash].trimEnd(), '~~~~', '');
  }
  return lines.join('\n');
}

function checkNotices(root) {
  const generated = renderNotices(root);
  const saved = fs.readFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8');
  if (saved !== generated)
    throw new Error('THIRD_PARTY_NOTICES.md is stale; run npm run licenses:generate');
}

module.exports = { renderNotices, checkNotices };
if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  if (process.argv.includes('--check')) checkNotices(root);
  else fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), renderNotices(root));
  console.log('Third-party notices match all locked packages.');
}
